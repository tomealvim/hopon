-- Dedicated warehouse with cost controls
USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS HOPON_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE RESOURCE MONITOR HOPON_RM
  WITH CREDIT_QUOTA = 10
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 80 PERCENT DO NOTIFY
    ON 100 PERCENT DO SUSPEND;

ALTER WAREHOUSE HOPON_WH SET RESOURCE_MONITOR = HOPON_RM;
