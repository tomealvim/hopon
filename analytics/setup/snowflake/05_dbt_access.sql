-- Key-pair auth and a least-privilege role for dbt
USE ROLE ACCOUNTADMIN;

-- Register the public key (the private key stays on the machine running dbt, never in the repo)
ALTER USER <YOUR_USER> SET RSA_PUBLIC_KEY = '<PUBLIC_KEY_BODY>';

CREATE ROLE IF NOT EXISTS TRANSFORMER;
GRANT ROLE TRANSFORMER TO USER <YOUR_USER>;

GRANT USAGE ON WAREHOUSE HOPON_WH TO ROLE TRANSFORMER;
GRANT USAGE ON DATABASE HOPON TO ROLE TRANSFORMER;

GRANT USAGE ON SCHEMA HOPON.RAW TO ROLE TRANSFORMER;
GRANT SELECT ON ALL TABLES IN SCHEMA HOPON.RAW TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA HOPON.RAW TO ROLE TRANSFORMER;

GRANT ALL ON SCHEMA HOPON.STAGING TO ROLE TRANSFORMER;
GRANT ALL ON SCHEMA HOPON.MARTS TO ROLE TRANSFORMER;
