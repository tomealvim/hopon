// Teste de upload de avatar para Cloudflare R2
const API_BASE = process.env.API_BASE || 'http://localhost:3000/api/v1';
const suffix = Date.now();

// 1. Registar utilizador de teste
const regRes = await fetch(`${API_BASE}/auth/register`, {
  method: 'POST',
  headers: { 'Content-Type': 'application/json' },
  body: JSON.stringify({
    email: `avatartest${suffix}@example.com`,
    password: 'Password123',
    name: 'Avatar Test',
  }),
});
const regData = await regRes.json();
const token = regData.accessToken;
console.log('1. Registo:', token ? '✅ token obtido' : `❌ ${JSON.stringify(regData)}`);
if (!token) process.exit(1);

// 2. Upload de avatar — JPEG mínimo válido (1x1 px)
const jpegBytes = Buffer.from([
  0xff,0xd8,0xff,0xe0,0x00,0x10,0x4a,0x46,0x49,0x46,0x00,0x01,0x01,0x00,0x00,0x01,
  0x00,0x01,0x00,0x00,0xff,0xdb,0x00,0x43,0x00,0x08,0x06,0x06,0x07,0x06,0x05,0x08,
  0x07,0x07,0x07,0x09,0x09,0x08,0x0a,0x0c,0x14,0x0d,0x0c,0x0b,0x0b,0x0c,0x19,0x12,
  0x13,0x0f,0x14,0x1d,0x1a,0x1f,0x1e,0x1d,0x1a,0x1c,0x1c,0x20,0x24,0x2e,0x27,0x20,
  0x22,0x2c,0x23,0x1c,0x1c,0x28,0x37,0x29,0x2c,0x30,0x31,0x34,0x34,0x34,0x1f,0x27,
  0x39,0x3d,0x38,0x32,0x3c,0x2e,0x33,0x34,0x32,0xff,0xc0,0x00,0x0b,0x08,0x00,0x01,
  0x00,0x01,0x01,0x01,0x11,0x00,0xff,0xc4,0x00,0x1f,0x00,0x00,0x01,0x05,0x01,0x01,
  0x01,0x01,0x01,0x01,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x01,0x02,0x03,0x04,
  0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0xff,0xda,0x00,0x08,0x01,0x01,0x00,0x00,0x3f,
  0x00,0xfb,0x76,0xa4,0xa2,0x80,0x3f,0xff,0xd9,
]);

const form = new FormData();
form.append('avatar', new Blob([jpegBytes], { type: 'image/jpeg' }), 'avatar.jpg');

const uploadRes = await fetch(`${API_BASE}/auth/me/avatar`, {
  method: 'POST',
  headers: { 'Authorization': `Bearer ${token}` },
  body: form,
});
const uploadData = await uploadRes.json();
console.log('2. Upload status:', uploadRes.status);

const avatarUrl = uploadData.profile?.avatarUrl;
if (avatarUrl) {
  console.log('3. avatarUrl:', avatarUrl);

  // 3. Verificar que o URL é acessível
  const imgRes = await fetch(avatarUrl);
  console.log('4. URL acessível:', imgRes.ok ? `✅ (${imgRes.status} ${imgRes.headers.get('content-type')})` : `❌ status ${imgRes.status}`);

  if (imgRes.ok) {
    console.log('\n🎉 R2 configurado corretamente!');
  } else {
    console.log('\n⚠️  Upload feito mas URL não acessível — verifica que o bucket tem Public Access ativo.');
  }
} else {
  console.log('❌ avatarUrl não retornado:', JSON.stringify(uploadData).slice(0, 300));
  process.exit(1);
}
